enum { SCREEN_WIDTH = 240, SCREEN_HEIGHT = 320 };
static uint16_t *s_framebuffer;

static uint16_t rgb565(unsigned r, unsigned g, unsigned b)
{
    const uint16_t color = (uint16_t)(((r & 0xf8) << 8) | ((g & 0xfc) << 3) | (b >> 3));
    return (uint16_t)((color << 8) | (color >> 8));
}

static esp_err_t ensure_framebuffer(void)
{
    if (!s_framebuffer)
    {
        s_framebuffer = heap_caps_malloc(SCREEN_WIDTH * SCREEN_HEIGHT * sizeof(uint16_t),
                                         MALLOC_CAP_SPIRAM | MALLOC_CAP_8BIT);
    }
    return s_framebuffer ? ESP_OK : ESP_ERR_NO_MEM;
}

static void fill_rect(int x, int y, int width, int height, uint16_t color)
{
    if (x < 0) { width += x; x = 0; }
    if (y < 0) { height += y; y = 0; }
    if (width <= 0 || height <= 0 || x >= SCREEN_WIDTH || y >= SCREEN_HEIGHT) return;
    if (width > SCREEN_WIDTH - x) width = SCREEN_WIDTH - x;
    if (height > SCREEN_HEIGHT - y) height = SCREEN_HEIGHT - y;
    for (int row = y; row < y + height; ++row)
    {
        for (int col = x; col < x + width; ++col)
        {
            s_framebuffer[row * SCREEN_WIDTH + col] = color;
        }
    }
}

static void round_rect(int x, int y, int width, int height, int radius, uint16_t color)
{
    if (width <= 0 || height <= 0) return;
    if (radius > width / 2) radius = width / 2;
    if (radius > height / 2) radius = height / 2;
    fill_rect(x + radius, y, width - 2 * radius, height, color);
    fill_rect(x, y + radius, width, height - 2 * radius, color);
    for (int cy = 0; cy < radius; ++cy)
    {
        for (int cx = 0; cx < radius; ++cx)
        {
            const int dx = radius - 1 - cx;
            const int dy = radius - 1 - cy;
            if (dx * dx + dy * dy <= radius * radius)
            {
                fill_rect(x + cx, y + cy, 1, 1, color);
                fill_rect(x + width - 1 - cx, y + cy, 1, 1, color);
                fill_rect(x + cx, y + height - 1 - cy, 1, 1, color);
                fill_rect(x + width - 1 - cx, y + height - 1 - cy, 1, 1, color);
            }
        }
    }
}

static void line(int x0, int y0, int x1, int y1, int thickness, uint16_t color)
{
    const int dx = x1 > x0 ? x1 - x0 : x0 - x1;
    const int sx = x0 < x1 ? 1 : -1;
    const int dy = y1 > y0 ? y0 - y1 : y1 - y0;
    const int sy = y0 < y1 ? 1 : -1;
    int error = dx + dy;
    for (;;)
    {
        fill_rect(x0 - thickness / 2, y0 - thickness / 2, thickness, thickness, color);
        if (x0 == x1 && y0 == y1) break;
        const int doubled = 2 * error;
        if (doubled >= dy) { error += dy; x0 += sx; }
        if (doubled <= dx) { error += dx; y0 += sy; }
    }
}

