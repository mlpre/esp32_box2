static uint32_t next_codepoint(const char **text)
{
    const uint8_t *p = (const uint8_t *)*text;
    uint32_t value = *p;
    size_t bytes = 1;
    if ((p[0] & 0xe0) == 0xc0 && p[1])
    {
        value = ((uint32_t)(p[0] & 0x1f) << 6) | (p[1] & 0x3f);
        bytes = 2;
    }
    else if ((p[0] & 0xf0) == 0xe0 && p[1] && p[2])
    {
        value = ((uint32_t)(p[0] & 0x0f) << 12) | ((uint32_t)(p[1] & 0x3f) << 6) | (p[2] & 0x3f);
        bytes = 3;
    }
    *text += bytes;
    return value;
}

static void draw_glyph(int x, int y, uint32_t codepoint, int font_size, int scale, uint16_t color)
{
    if (codepoint < 128)
    {
        const uint8_t *columns = ascii_glyph((char)codepoint);
        y += (font_size - 7) * scale / 2;
        for (int col = 0; col < 5; ++col)
        {
            for (int row = 0; row < 7; ++row)
            {
                if (columns[col] & (1U << row))
                    fill_rect(x + col * scale, y + row * scale, scale, scale, color);
            }
        }
        return;
    }
    for (size_t i = 0; i < sizeof(s_chinese_glyphs) / sizeof(s_chinese_glyphs[0]); ++i)
    {
        if (s_chinese_glyphs[i].codepoint != codepoint) continue;
        const uint16_t *rows = font_size == 12 ? s_chinese_glyphs[i].small : s_chinese_glyphs[i].normal;
        for (int row = 0; row < font_size; ++row)
        {
            for (int col = 0; col < font_size; ++col)
            {
                if (rows[row] & (1U << col))
                    fill_rect(x + col * scale, y + row * scale, scale, scale, color);
            }
        }
        return;
    }
}

static int text_width(const char *text, int font_size, int scale)
{
    int width = 0;
    while (*text) width += (next_codepoint(&text) < 128 ? 6 : font_size) * scale;
    return width;
}

static void text(int x, int y, const char *caption, int font_size, int scale, uint16_t color)
{
    while (*caption)
    {
        const uint32_t codepoint = next_codepoint(&caption);
        draw_glyph(x, y, codepoint, font_size, scale, color);
        x += (codepoint < 128 ? 6 : font_size) * scale;
    }
}

static void centered(int x, int y, int width, const char *caption, int font_size, int scale, uint16_t color)
{
    text(x + (width - text_width(caption, font_size, scale)) / 2, y, caption, font_size, scale, color);
}

static int clamp(int value, int minimum, int maximum)
{
    return value < minimum ? minimum : value > maximum ? maximum : value;
}

